// Generates src/lib/decks/anagrams.js — the Anagrams rack deck.
//
// Racks are common 7-letter words (src/lib/commonWords.js) whose letters
// make at least MIN_COMMON_SOLUTIONS everyday, family-safe words, so every
// rack has plenty to find and the reveal's "words you missed" leads with
// words players know. Valid words are every 3–7 letter Word Hunt dictionary
// word (public/wordhunt-dict.txt, already scrubbed of banned words) buildable
// from a chosen rack, so obscure-but-real finds still count.
//
// Run: node scripts/build-anagram-racks.mjs
import { register } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

// src/lib uses Vite-style extensionless imports; resolve them for Node.
register('data:text/javascript,' + encodeURIComponent(`
  export async function resolve(specifier, context, next) {
    try { return await next(specifier, context) } catch (err) {
      if (/^\\.\\.?\\//.test(specifier)) return next(specifier + '.js', context)
      throw err
    }
  }
`))

const { COMMON_WORDS, isCommonWord } = await import('../src/lib/commonWords.js')
const { isBannedWord, isFamilySafe } = await import('../src/lib/wordDenylist.js')
const { canBuildWord, MIN_SOLUTION_COUNT, RACK_SIZE, MIN_WORD_LENGTH } = await import('../src/lib/anagramsLogic.js')

// Everyday, family-safe solutions a rack must offer.
const MIN_COMMON_SOLUTIONS = 12
// Cap on 7-letter solutions: one bingo is worth 16 three-letter words, so a
// rack with many full-length anagrams is decided by who spots them first.
const MAX_BINGOS = 2
// How many racks to ship (the best by common-solution count).
const DECK_SIZE = 90

const root = fileURLToPath(new URL('..', import.meta.url))
const dict = readFileSync(`${root}public/wordhunt-dict.txt`, 'utf8')
  .split('\n')
  .map(w => w.trim())
  .filter(w => w.length >= MIN_WORD_LENGTH && w.length <= RACK_SIZE && !isBannedWord(w))
const dictSet = new Set(dict)

const seenKeys = new Set()
const racks = []
for (const word of COMMON_WORDS) {
  if (word.length !== RACK_SIZE || !dictSet.has(word) || !isFamilySafe(word)) continue
  const key = [...word].sort().join('')
  if (seenKeys.has(key)) continue
  const solutions = dict.filter(w => canBuildWord(w, word))
  const common = solutions.filter(w => isCommonWord(w) && isFamilySafe(w))
  const bingos = solutions.filter(w => w.length === RACK_SIZE)
  if (solutions.length < MIN_SOLUTION_COUNT || common.length < MIN_COMMON_SOLUTIONS || bingos.length > MAX_BINGOS) continue
  seenKeys.add(key)
  racks.push({ word, solutions, common: common.length })
}

racks.sort((a, b) => b.common - a.common || a.word.localeCompare(b.word))
const chosen = racks.slice(0, DECK_SIZE).sort((a, b) => a.word.localeCompare(b.word))
const valid = [...new Set(chosen.flatMap(r => r.solutions))].sort()

const wrap = (words, quote) => {
  const lines = []
  let line = ''
  for (const w of words) {
    const item = quote ? `'${w}', ` : `${w} `
    if ((line + item).length > 96) { lines.push(line.trimEnd()); line = '' }
    line += item
  }
  if (line) lines.push(line.trimEnd())
  return lines.map(l => `  ${l}`).join('\n')
}

const out = `// Anagrams rack deck — GENERATED by scripts/build-anagram-racks.mjs; do not
// edit by hand (re-run the script after changing its sources).
//
// ${chosen.length} racks: common 7-letter words, each with at least ${MIN_COMMON_SOLUTIONS} everyday
// family-safe solutions and at most ${MAX_BINGOS} seven-letter anagrams. Valid words are every
// 3–7 letter Word Hunt dictionary word buildable from some rack (${valid.length} words).

export const ANAGRAM_RACK_WORDS = [
${wrap(chosen.map(r => r.word), true)}
]

export const ANAGRAM_VALID_WORDS = \`
${wrap(valid, false)}
\`.split(/\\s+/).filter(Boolean)
`
writeFileSync(`${root}src/lib/decks/anagrams.js`, out)
console.log(`eligible racks: ${racks.length}; shipped: ${chosen.length}; valid words: ${valid.length}`)
console.log('common-solution counts:', chosen.map(r => r.common).sort((a, b) => a - b).join(' '))
