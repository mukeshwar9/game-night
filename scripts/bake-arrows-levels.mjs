// Bakes the finished boards of Arrows solo levels 21+ into
// src/lib/arrowsLevelsBaked.js.
//
//   node scripts/bake-arrows-levels.mjs
//
// Each level is generated from its spec + seed (ARROWS_LEVEL_SPECS and
// ARROWS_LEVEL_SEEDS in src/lib/arrowsLevelsLogic.js, seeds picked by
// scripts/pick-arrows-levels.mjs), checked with the solver, and written out
// as plain data. Players get exactly these boards even if the generator
// changes later; rerun this only when you mean to change those levels.

import fs from 'node:fs'
import { generateArrowsLevel, solveArrows } from '../src/lib/arrowsLogic.js'
import { ARROWS_GENERATED_LEVELS, ARROWS_LEVEL_SEEDS, ARROWS_LEVEL_SPECS, levelMeetsIntro } from '../src/lib/arrowsLevelsLogic.js'

const out = []
for (let n = ARROWS_GENERATED_LEVELS + 1; n <= ARROWS_LEVEL_SPECS.length; n += 1) {
  const spec = { ...ARROWS_LEVEL_SPECS[n - 1], name: `level-${n}` }
  const level = generateArrowsLevel(ARROWS_LEVEL_SEEDS[n - 1], spec)
  if (!solveArrows(level).solvable) throw new Error(`level ${n} is not solvable`)
  if (!levelMeetsIntro(spec, level)) throw new Error(`level ${n} is missing a piece its spec asks for`)
  const arrows = level.arrows.map((a) => `      ${JSON.stringify(a)},`).join('\n')
  const pieces = ['mirrors', 'crates'].filter((k) => level[k]).map((k) => `\n    ${k}: ${JSON.stringify(level[k])},`).join('')
  out.push(`  ${n}: {\n    cols: ${level.cols},\n    rows: ${level.rows},\n    arrows: [\n${arrows}\n    ],${pieces}\n  },`)
}
const file = new URL('../src/lib/arrowsLevelsBaked.js', import.meta.url)
fs.writeFileSync(file, `// Generated by scripts/bake-arrows-levels.mjs — do not edit by hand.
// The finished boards of Arrows solo levels ${ARROWS_GENERATED_LEVELS + 1}–${ARROWS_LEVEL_SPECS.length}: { cols, rows, arrows, mirrors?, crates? }.
export const ARROWS_BAKED_LEVELS = {
${out.join('\n')}
}
`)
console.log(`baked ${out.length} levels`)
