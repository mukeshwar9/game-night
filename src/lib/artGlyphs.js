// The strokes of `text` as polylines in pixel space: baseline-top-left at (x, y),
// letters h tall, `gap` of a letter width between them.
export function textStrokes(text, x, y, h, gap = 0.28) {
  const w = h * GLYPH_ASPECT
  const out = []
  ;[...text].forEach((ch, i) => {
    const g = GLYPHS[ch.toUpperCase()]
    if (!g) return
    const ox = x + i * w * (1 + gap)
    for (const line of g) out.push(line.map(([u, v]) => [ox + u * w, y + v * h]))
  })
  return out
}

export const textWidth = (text, h, gap = 0.28) => h * GLYPH_ASPECT * ((1 + gap) * text.length - gap)
